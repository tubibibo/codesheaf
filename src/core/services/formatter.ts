import type { BundleFormat, BundledFile } from '../domain/bundle';
import { escapeXmlAttribute, toCdata, longestBacktickRun, withLineNumbers } from '../utils/text';
import { formatTokenCount } from '../utils/format';

/** Everything the renderer needs — precomputed by the bundle builder. */
export interface RenderInput {
  readonly files: readonly BundledFile[];
  readonly tree: string;
  readonly format: BundleFormat;
  readonly includeLineNumbers: boolean;
  readonly includeTree: boolean;
  /** Display string such as `CodeSheaf v1.0.0`. */
  readonly generator: string;
}

/** Renders the final bundle text in the requested format. */
export function renderBundle(input: RenderInput): string {
  switch (input.format) {
    case 'xml':
      return renderXml(input);
    case 'plain':
      return renderPlain(input);
    case 'markdown':
    default:
      return renderMarkdown(input);
  }
}

function totalTokens(files: readonly BundledFile[]): number {
  return files.reduce((sum, f) => sum + f.estimatedTokens, 0);
}

function bodyOf(file: BundledFile, includeLineNumbers: boolean): string {
  return includeLineNumbers ? withLineNumbers(file.content) : file.content;
}

function renderMarkdown(input: RenderInput): string {
  const { files, tree, includeLineNumbers, includeTree, generator } = input;
  const parts: string[] = [];
  parts.push('# CodeSheaf Context Bundle');
  parts.push('');
  parts.push(
    `> ${files.length} file(s) · ~${formatTokenCount(totalTokens(files))} estimated tokens · generated by ${generator}`,
  );
  parts.push('');
  if (includeTree && tree.length > 0) {
    parts.push('## Project Tree', '', '```text', tree, '```', '');
  }
  for (const file of files) {
    parts.push(`## ${file.path}`, '', fencedCodeBlock(file, includeLineNumbers), '');
  }
  return `${parts.join('\n').trimEnd()}\n`;
}

function fencedCodeBlock(file: BundledFile, includeLineNumbers: boolean): string {
  const body = bodyOf(file, includeLineNumbers);
  const fence = '`'.repeat(Math.max(3, longestBacktickRun(body) + 1));
  return `${fence}${fenceLanguage(file.languageId)}\n${body}\n${fence}`;
}

function fenceLanguage(languageId: string): string {
  switch (languageId) {
    case 'typescript':
    case 'typescriptreact':
      return 'ts';
    case 'javascript':
    case 'javascriptreact':
      return 'js';
    case 'shellscript':
      return 'bash';
    case 'csharp':
      return 'csharp';
    case 'plaintext':
      return '';
    default:
      return languageId;
  }
}

function renderXml(input: RenderInput): string {
  const { files, tree, includeLineNumbers, includeTree, generator } = input;
  const lines: string[] = [];
  lines.push(
    `<codesheaf generator="${escapeXmlAttribute(generator)}" files="${files.length}" estimated_tokens="${totalTokens(files)}">`,
  );
  if (includeTree && tree.length > 0) {
    lines.push(`  <tree>${toCdata(tree)}</tree>`);
  }
  for (const file of files) {
    lines.push(
      `  <file path="${escapeXmlAttribute(file.path)}" language="${escapeXmlAttribute(file.languageId)}" origin="${file.origin}" tokens="${file.estimatedTokens}">`,
    );
    lines.push(`    ${toCdata(bodyOf(file, includeLineNumbers))}`);
    lines.push('  </file>');
  }
  lines.push('</codesheaf>');
  return `${lines.join('\n')}\n`;
}

function renderPlain(input: RenderInput): string {
  const { files, tree, includeLineNumbers, includeTree, generator } = input;
  const separator = '='.repeat(78);
  const parts: string[] = [];
  parts.push(separator);
  parts.push(
    `CodeSheaf Context Bundle — ${files.length} file(s) · ~${formatTokenCount(totalTokens(files))} tokens · ${generator}`,
  );
  parts.push(separator);
  parts.push('');
  if (includeTree && tree.length > 0) {
    parts.push('PROJECT TREE:', tree, '');
  }
  for (const file of files) {
    parts.push(separator);
    parts.push(`FILE: ${file.path} (${file.languageId})`);
    parts.push(separator);
    parts.push(bodyOf(file, includeLineNumbers));
    parts.push('');
  }
  return `${parts.join('\n').trimEnd()}\n`;
}

import { describe, expect, it } from 'vitest';
import type { BundledFile } from '../../src/core/domain/bundle';
import { renderBundle, type RenderInput } from '../../src/core/services/formatter';

function makeFile(overrides: Partial<BundledFile> = {}): BundledFile {
  return {
    path: 'src/a.ts',
    absolutePath: 'C:/proj/src/a.ts',
    languageId: 'typescript',
    content: 'const x = 1;',
    origin: 'explicit',
    chars: 12,
    estimatedTokens: 3,
    ...overrides,
  };
}

function makeInput(overrides: Partial<RenderInput> = {}): RenderInput {
  return {
    files: [makeFile()],
    tree: 'project/\n└── src/',
    format: 'markdown',
    includeLineNumbers: false,
    includeTree: false,
    generator: 'CodeSheaf v1.0.0',
    ...overrides,
  };
}

describe('renderBundle (markdown)', () => {
  it('renders a header, per-file sections and fenced code blocks', () => {
    const out = renderBundle(makeInput());
    expect(out).toContain('# CodeSheaf Context Bundle');
    expect(out).toContain('> 1 file(s) · ~3 estimated tokens · generated by CodeSheaf v1.0.0');
    expect(out).toContain('## src/a.ts');
    expect(out).toContain('```ts\nconst x = 1;\n```');
  });

  it('includes the project tree only when requested', () => {
    expect(renderBundle(makeInput({ includeTree: true }))).toContain('```text\nproject/');
    expect(renderBundle(makeInput({ includeTree: false }))).not.toContain('```text');
  });

  it('escapes content that itself contains backtick fences', () => {
    const tricky = makeFile({ content: '```\nraw\n```' });
    const out = renderBundle(makeInput({ files: [tricky] }));
    expect(out).toContain('````ts\n```\nraw\n```\n````');
  });

  it('supports line numbers', () => {
    const twoLines = makeFile({ content: 'a\nbc' });
    const out = renderBundle(makeInput({ files: [twoLines], includeLineNumbers: true }));
    expect(out).toContain('1 | a\n2 | bc');
  });

  it('renders the plaintext language without a fence suffix', () => {
    const plain = makeFile({ languageId: 'plaintext', content: 'hello' });
    expect(renderBundle(makeInput({ files: [plain] }))).toContain('```\nhello\n```');
  });
});

describe('renderBundle (xml)', () => {
  it('renders attributes and CDATA sections', () => {
    const out = renderBundle(makeInput({ format: 'xml', includeTree: true }));
    expect(out).toContain(
      '<codesheaf generator="CodeSheaf v1.0.0" files="1" estimated_tokens="3">',
    );
    expect(out).toContain(
      '<file path="src/a.ts" language="typescript" origin="explicit" tokens="3">',
    );
    expect(out).toContain('<![CDATA[const x = 1;]]>');
    expect(out).toContain('<tree><![CDATA[project/');
  });

  it('escapes XML-special characters in attributes and defuses CDATA terminators', () => {
    const tricky = makeFile({ path: 'src/a"b.ts', content: 'x = a<b && c]]> d' });
    const out = renderBundle(makeInput({ files: [tricky], format: 'xml' }));
    expect(out).toContain('path="src/a&quot;b.ts"');
    expect(out).toContain(']]]]><![CDATA[> d');
  });
});

describe('renderBundle (plain)', () => {
  it('renders separators, file headers and the tree', () => {
    const out = renderBundle(makeInput({ format: 'plain', includeTree: true }));
    expect(out).toContain('CodeSheaf Context Bundle — 1 file(s)');
    expect(out).toContain('PROJECT TREE:');
    expect(out).toContain('FILE: src/a.ts (typescript)');
    expect(out).toContain('const x = 1;');
  });
});
